#!/usr/bin/env node
/**
 * Put a project's files on the site, converted to the site's standards.
 *
 *   npm run media -- inventory <dir>
 *   npm run media -- add <slug> <dir> --thumbnail <file> [files…]   (--thumbnail optional if the project has one)
 *   npm run media -- zip <slug> <dir> --name "<label>" <paths…>
 *   npm run media -- remove <slug> [original-file-name]
 *   npm run media -- next-id
 *
 * Output goes to `public/media/<slug>/` and is recorded in
 * `src/data/media-manifest.js` (figures, reports, zips) and
 * `src/data/cover-manifest.js` (the card thumbnail). The source folder is only
 * ever read.
 *
 * Thumbnail : WebP q80, at most 900px wide (a 370px card on a 2x display).
 * Images    : WebP, at most 1600px wide. PNG -> lossless, so one-pixel axis
 *             lines in plots stay sharp; JPEG/HEIC photos -> q82.
 * PDFs      : Ghostscript downsample to 300 dpi, kept only if smaller with the
 *             same page count; encrypted PDFs are copied untouched.
 * Videos    : refused. They go on YouTube.
 */
import { execFile } from "node:child_process";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

import { PROJECTS, RETIRED_IDS } from "../src/data/content.js";
import MEDIA from "../src/data/media-manifest.js";
import COVERS from "../src/data/cover-manifest.js";
import { nextProjectId } from "../src/lib/projects.js";
import { classify, planOutputs, safeName, serialiseManifest } from "./lib/media-rules.mjs";

const run = promisify(execFile);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "public");
const MEDIA_FILE = path.join(ROOT, "src", "data", "media-manifest.js");
const COVER_FILE = path.join(ROOT, "src", "data", "cover-manifest.js");

const MEDIA_HEADER = [
  "// GENERATED by scripts/media.mjs — do not edit by hand.",
  "// Maps project slug -> source file name -> path under public/.",
  "// A file absent from here has no asset, so the page falls back to a",
  "// labelled placeholder slot rather than a broken image.",
];
const COVER_HEADER = [
  "// GENERATED by scripts/media.mjs — do not edit by hand.",
  "// Project card thumbnails: slug -> path under public/ and pixel size.",
];

const MAX_WIDTH = 1600;
const THUMB_WIDTH = 900;

function die(msg) {
  console.error(`ERROR: ${msg}`);
  process.exit(1);
}

const fmt = (bytes) => (bytes > 1048576 ? `${(bytes / 1048576).toFixed(1)} MB` : `${Math.round(bytes / 1024)} KB`);

async function exists(p) {
  return fs.access(p).then(
    () => true,
    () => false,
  );
}

/** Every file under dir, relative, skipping dotfiles and macOS debris. */
async function walk(dir, rel = "") {
  const out = [];
  for (const e of await fs.readdir(path.join(dir, rel), { withFileTypes: true })) {
    if (e.name.startsWith(".") || e.name === "__MACOSX") continue;
    const r = path.join(rel, e.name);
    if (e.isDirectory()) out.push(...(await walk(dir, r)));
    else out.push(r);
  }
  return out.sort();
}

async function imageSize(file) {
  const { stdout } = await run("sips", ["-g", "pixelWidth", "-g", "pixelHeight", file]);
  return {
    w: Number(stdout.match(/pixelWidth:\s*(\d+)/)?.[1] ?? 0),
    h: Number(stdout.match(/pixelHeight:\s*(\d+)/)?.[1] ?? 0),
  };
}

async function pdfInfo(file) {
  try {
    const { stdout } = await run("pdfinfo", [file]);
    return {
      pages: Number(stdout.match(/^Pages:\s*(\d+)/m)?.[1] ?? 0),
      // Ghostscript would silently re-write an encrypted PDF without its
      // permission flags. Stripping a document's own restrictions is not ours
      // to do, so these are copied through untouched.
      encrypted: !/^Encrypted:\s*no/m.test(stdout),
    };
  } catch {
    return { pages: 0, encrypted: false };
  }
}

function aspectOf(w, h) {
  const r = w / h;
  if (Math.abs(r - 4 / 3) / (4 / 3) < 0.02) return "4 / 3";
  if (Math.abs(r - 16 / 9) / (16 / 9) < 0.02) return "16 / 9";
  return `${w} / ${h}`;
}

async function videoInfo(file) {
  try {
    const { stdout } = await run("ffprobe", [
      "-v", "error", "-select_streams", "v:0",
      "-show_entries", "stream=width,height:format=duration", "-of", "json", file,
    ]);
    const j = JSON.parse(stdout);
    const { width: w, height: h } = j.streams?.[0] ?? {};
    return `${Math.round(Number(j.format?.duration ?? 0))}s, ${w}×${h}, aspect ${w && h ? aspectOf(w, h) : "?"}`;
  } catch {
    return "unreadable";
  }
}

/* --- inventory ------------------------------------------------------------ */

async function inventory(dir) {
  if (!dir || !(await exists(dir))) die(`No such folder: ${dir}`);
  const files = await walk(dir);
  console.log(`${files.length} file(s) in ${dir}\n`);
  for (const rel of files) {
    const abs = path.join(dir, rel);
    const kind = classify(rel);
    const { size } = await fs.stat(abs);
    let detail = "";
    if (kind === "image") {
      const { w, h } = await imageSize(abs);
      detail = `${w}×${h}`;
    } else if (kind === "pdf") {
      const { pages, encrypted } = await pdfInfo(abs);
      detail = `${pages} pages${encrypted ? ", encrypted" : ""}`;
    } else if (kind === "video") {
      detail = await videoInfo(abs);
    }
    console.log(`${rel.padEnd(48)} ${kind.padEnd(8)} ${fmt(size).padStart(8)}  ${detail}`);
  }
}

/* --- conversion ----------------------------------------------------------- */

/** Resize (if wider than maxWidth) and encode to WebP. Returns output size. */
async function toWebp(src, out, { maxWidth, lossless, quality }) {
  const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), "media-"));
  try {
    let input = src;
    let { w, h } = await imageSize(src);
    // cwebp can't read HEIC, and resizes only from its own decode path, so
    // sips produces an intermediate PNG for both cases.
    if (w > maxWidth || path.extname(src).toLowerCase() === ".heic") {
      input = path.join(tmpDir, "in.png");
      const args = ["-s", "format", "png", src, "--out", input];
      if (w > maxWidth) args.unshift("--resampleWidth", String(maxWidth));
      await run("sips", args);
      ({ w, h } = await imageSize(input));
    }
    const enc = lossless ? ["-lossless", "-z", "9"] : ["-q", String(quality), "-m", "6", "-sharp_yuv"];
    await run("cwebp", ["-quiet", ...enc, input, "-o", out]);
    return { w, h };
  } finally {
    await fs.rm(tmpDir, { recursive: true, force: true });
  }
}

async function processPdf(src, out) {
  const { size } = await fs.stat(src);
  const { pages: pagesIn, encrypted } = await pdfInfo(src);
  if (encrypted) {
    await fs.copyFile(src, out);
    return { pages: pagesIn, note: "encrypted, copied untouched" };
  }

  const tmp = path.join(os.tmpdir(), `media-${process.pid}-${path.basename(out)}`);
  let note = "";
  let useCompressed = false;
  try {
    await run("gs", [
      "-sDEVICE=pdfwrite",
      "-dSAFER",
      "-dCompatibilityLevel=1.7",
      /* 300 dpi, print grade. Reports embed matplotlib plots whose axis lines
         and tick labels are one pixel wide; 150 dpi visibly softened them.
         /printer for its image quality, with the knobs pinned so a future
         Ghostscript can't change the preset. Threshold 1.0 downsamples
         anything above target. */
      "-dPDFSETTINGS=/printer",
      "-dDetectDuplicateImages=true",
      "-dDownsampleColorImages=true",
      "-dColorImageResolution=300",
      "-dColorImageDownsampleThreshold=1.0",
      "-dDownsampleGrayImages=true",
      "-dGrayImageResolution=300",
      "-dGrayImageDownsampleThreshold=1.0",
      "-dDownsampleMonoImages=true",
      "-dMonoImageResolution=600",
      "-dNOPAUSE",
      "-dQUIET",
      "-dBATCH",
      `-sOutputFile=${tmp}`,
      src,
    ]);
    // Only accept a result that is smaller AND still has every page.
    const [{ size: outSize }, { pages: pagesOut }] = await Promise.all([fs.stat(tmp), pdfInfo(tmp)]);
    useCompressed = pagesOut === pagesIn && pagesOut > 0 && outSize < size;
    if (!useCompressed) note = "compression gained nothing, original kept";
  } catch (err) {
    note = `ghostscript failed, original kept — ${err.message.split("\n")[0]}`;
  }

  if (useCompressed) await fs.rename(tmp, out);
  else {
    await fs.rm(tmp, { force: true });
    await fs.copyFile(src, out);
  }
  return { pages: pagesIn, note };
}

async function writeManifests() {
  await fs.writeFile(MEDIA_FILE, serialiseManifest(MEDIA_HEADER, MEDIA));
  await fs.writeFile(COVER_FILE, serialiseManifest(COVER_HEADER, COVERS));
}

function checkSlug(slug) {
  if (!/^p-\d{3}$/.test(slug || "")) die(`Slug must look like p-018, got "${slug}"`);
}

function parseFlags(args, names) {
  const flags = {};
  const rest = [];
  for (let i = 0; i < args.length; i++) {
    const name = args[i].replace(/^--/, "");
    if (args[i].startsWith("--") && names.includes(name)) flags[name] = args[++i];
    else rest.push(args[i]);
  }
  return { flags, rest };
}

/* --- add ------------------------------------------------------------------ */

async function add(args) {
  const { flags, rest } = parseFlags(args, ["thumbnail"]);
  const [slug, dir, ...listed] = rest;
  checkSlug(slug);
  if (!dir || !(await exists(dir))) die(`No such folder: ${dir}`);

  const files = listed.length
    ? listed
    : (await walk(dir)).filter((f) => f !== flags.thumbnail && ["image", "pdf"].includes(classify(f)));

  for (const f of [...files, flags.thumbnail].filter(Boolean)) {
    if (!(await exists(path.join(dir, f)))) die(`Not in ${dir}: ${f}`);
  }

  // An existing project already has its card thumbnail; adding a figure later needn't resend it.
  const { outputs, errors } = planOutputs(files, { thumbnail: flags.thumbnail, hasCover: Boolean(COVERS[slug]) });
  if (errors.length) die(`Nothing written:\n  ${errors.join("\n  ")}`);

  const outDir = path.join(PUBLIC, "media", slug);
  await fs.mkdir(outDir, { recursive: true });
  MEDIA[slug] ??= {};

  for (const o of outputs) {
    const src = path.join(dir, o.src);
    const out = path.join(outDir, o.out);
    const rel = path.relative(PUBLIC, out);
    const { size: before } = await fs.stat(src);
    let extra = "";

    if (o.kind === "thumbnail") {
      const { w, h } = await toWebp(src, out, { maxWidth: THUMB_WIDTH, lossless: false, quality: 80 });
      COVERS[slug] = { path: rel, w, h };
      extra = `${w}×${h}`;
    } else if (o.kind === "image") {
      const { w, h } = await toWebp(src, out, { maxWidth: MAX_WIDTH, lossless: o.lossless, quality: 82 });
      MEDIA[slug][path.basename(o.src)] = { path: rel, w, h };
      extra = `${w}×${h}${o.lossless ? ", lossless" : ""}`;
    } else if (o.kind === "pdf") {
      const { pages, note } = await processPdf(src, out);
      MEDIA[slug][path.basename(o.src)] = { path: rel, pages };
      extra = `${pages} pages${note ? `, ${note}` : ""}`;
    } else {
      await fs.copyFile(src, out);
      MEDIA[slug][path.basename(o.src)] = { path: rel };
    }

    const { size: after } = await fs.stat(out);
    console.log(`${o.src} -> public/${rel}  (${fmt(before)} -> ${fmt(after)}${extra ? `, ${extra}` : ""})`);
  }

  await writeManifests();
  console.log(`\nManifest keys for content.js (file: "…"):\n  ${Object.keys(MEDIA[slug]).join("\n  ")}`);
}

/* --- zip ------------------------------------------------------------------ */

async function zip(args) {
  const { flags, rest } = parseFlags(args, ["name"]);
  const [slug, dir, ...paths] = rest;
  checkSlug(slug);
  if (!flags.name) die('Give the download a name: --name "Source code"');
  if (!paths.length) die("List the files or folders to bundle.");
  const key = safeName(`${flags.name}.zip`);
  const outDir = path.join(PUBLIC, "media", slug);
  const out = path.join(outDir, key);
  await fs.mkdir(outDir, { recursive: true });
  await fs.rm(out, { force: true });
  await run(
    "zip",
    ["-r", "-X", "-q", out, ...paths, "-x", "*.DS_Store", "*__MACOSX*", "*__pycache__*", "*node_modules*", "*.git/*"],
    { cwd: dir },
  );
  const { stdout } = await run("zipinfo", ["-1", out]);
  MEDIA[slug] ??= {};
  MEDIA[slug][key] = { path: path.relative(PUBLIC, out) };
  await writeManifests();
  const entries = stdout.trim().split("\n");
  console.log(`public/media/${slug}/${key}  (${fmt((await fs.stat(out)).size)}, ${entries.length} entries)`);
  console.log(entries.map((e) => `  ${e}`).join("\n"));
  console.log(`\nManifest key for content.js: file: "${key}"`);
}

/* --- remove --------------------------------------------------------------- */

async function remove([slug, file]) {
  checkSlug(slug);
  if (file) {
    const entry = MEDIA[slug]?.[file];
    if (!entry) die(`${slug} has no manifest entry "${file}". Keys: ${Object.keys(MEDIA[slug] ?? {}).join(", ")}`);
    await fs.rm(path.join(PUBLIC, entry.path), { force: true });
    delete MEDIA[slug][file];
    if (!Object.keys(MEDIA[slug]).length) delete MEDIA[slug];
    console.log(`Removed ${entry.path}`);
  } else {
    await fs.rm(path.join(PUBLIC, "media", slug), { recursive: true, force: true });
    delete MEDIA[slug];
    delete COVERS[slug];
    console.log(`Removed public/media/${slug}/ and its manifest entries`);
  }
  await writeManifests();
}

/* --- main ----------------------------------------------------------------- */

const [cmd, ...args] = process.argv.slice(2);
const commands = {
  inventory: () => inventory(args[0]),
  add: () => add(args),
  zip: () => zip(args),
  remove: () => remove(args),
  "next-id": async () => console.log(nextProjectId(PROJECTS, RETIRED_IDS)),
};

if (!commands[cmd]) {
  console.error("Usage: npm run media -- {inventory <dir> | add <slug> <dir> --thumbnail <f> [files…] | zip <slug> <dir> --name <n> <paths…> | remove <slug> [file] | next-id}");
  process.exit(2);
}
commands[cmd]().catch((err) => die(err.stack || err.message));
